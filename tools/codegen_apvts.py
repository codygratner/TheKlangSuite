#!/usr/bin/env python3
"""
tools/codegen_apvts.py — Single Source of Truth APVTS Code Generator
================================================================================
Reads a declarative plugin parameter contract (contracts/<plugin>.yaml) and
generates:
  1. Source/<plugin>/<Plugin>ParameterIds.h (constexpr typed identifiers)
  2. Source/<plugin>/<Plugin>ParameterLayout.h (complete JUCE ParameterLayout generator)

Also provides:
  --verify: Asserts that on-disk C++ matches the contract (exit 0 on match, 1 on drift)
  --plugin <name>: Targets a specific plugin
  --all: Generates code for all YAML contracts in contracts/

Machine Invariants:
  - Universal UTF-8 Invariant
  - Zero Ghost Controls (compile-time checked constexpr IDs)
"""

import sys
import argparse
from pathlib import Path
import yaml

# Universal UTF-8 console output
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")
if hasattr(sys.stderr, "reconfigure"):
    sys.stderr.reconfigure(encoding="utf-8")

ROOT_VAULT = Path(r"C:\_\Vault")
ROOT_TKS = Path(r"C:\Dev\TheKlangSuite")


def load_contract(plugin_name: str) -> dict:
    candidates = [
        ROOT_TKS / "contracts" / f"{plugin_name.lower()}.yaml",
        ROOT_VAULT / "contracts" / f"{plugin_name.lower()}.yaml",
    ]
    for c in candidates:
        if c.exists():
            with open(c, "r", encoding="utf-8") as f:
                return yaml.safe_load(f)
    raise FileNotFoundError(f"Contract for plugin '{plugin_name}' not found in contracts/")


def resolve_plugin_prefix(plugin: str) -> str:
    target_dir = ROOT_TKS / "source" / plugin.lower()
    pascal = plugin[:1].upper() + plugin[1:]
    target_name = f"{pascal}ParameterIds.h"
    if target_dir.exists() and any(f.name == target_name for f in target_dir.iterdir()):
        return pascal
    return plugin

def generate_ids_header(contract: dict) -> str:
    plugin = contract["plugin"]
    ns = f"{plugin}Parameters"
    params = contract.get("parameters", [])

    lines = [
        "// ==============================================================================",
        f"// {plugin}ParameterIds.h",
        "// AUTOGENERATED BY tools/codegen_apvts.py — DO NOT EDIT DIRECTLY",
        f"// Source Contract: contracts/{plugin.lower()}.yaml",
        "// ==============================================================================",
        "#pragma once",
        "",
        f"namespace {ns} {{",
        "namespace Ids {",
    ]

    for p in params:
        pid = p["id"]
        lines.append(f'    constexpr auto {pid} = "{pid}";')

    lines.extend([
        "} // namespace Ids",
        "",
        "namespace Names {",
    ])

    for p in params:
        pid = p["id"]
        pname = p["name"].replace('"', '\\"')
        lines.append(f'    constexpr auto {pid} = "{pname}";')

    lines.extend([
        "} // namespace Names",
        "",
        "namespace Total {",
        f"    constexpr int count = {len(params)};",
        "} // namespace Total",
        f"}} // namespace {ns}",
        ""
    ])

    return "\n".join(lines)


def generate_layout_header(contract: dict) -> str:
    plugin = contract["plugin"]
    ns = f"{plugin}Parameters"
    params = contract.get("parameters", [])

    prefix = resolve_plugin_prefix(plugin)
    lines = [
        "// ==============================================================================",
        f"// {prefix}ParameterLayout.h",
        "// AUTOGENERATED BY tools/codegen_apvts.py — DO NOT EDIT DIRECTLY",
        f"// Source Contract: contracts/{plugin.lower()}.yaml",
        "// ==============================================================================",
        "#pragma once",
        "",
        '#include <juce_audio_processors/juce_audio_processors.h>',
        f'#include "{prefix}ParameterIds.h"',
        "",
        f"namespace {ns} {{",
        "",
        "inline juce::AudioProcessorValueTreeState::ParameterLayout createLayout() {",
        "    juce::AudioProcessorValueTreeState::ParameterLayout layout;",
        "",
        "    // S-Curve Octave Detent Range Lambda (-1..0..+2 Oct with 12 o'clock detent at 0.00)",
        "    auto sCurveOctaveRange = []() {",
        "        return juce::NormalisableRange<float>(",
        "            -1.0f, 2.0f,",
        "            [](float, float, float norm) {",
        "                if (norm <= 0.5f) {",
        "                    float t = norm * 2.0f;",
        "                    float s = t * t * (3.0f - 2.0f * t);",
        "                    return -1.0f * (1.0f - s);",
        "                } else {",
        "                    float t = (norm - 0.5f) * 2.0f;",
        "                    float s = t * t * (3.0f - 2.0f * t);",
        "                    return 2.0f * s;",
        "                }",
        "            },",
        "            [](float, float, float val) {",
        "                if (val <= 0.0f) {",
        "                    float s = std::clamp((val - (-1.0f)) / 1.0f, 0.0f, 1.0f);",
        "                    float t = s;",
        "                    for (int i = 0; i < 4; ++i) {",
        "                        float f = t * t * (3.0f - 2.0f * t) - s;",
        "                        float df = 6.0f * t * (1.0f - t);",
        "                        if (std::abs(df) > 1e-5f) t -= f / df;",
        "                        t = std::clamp(t, 0.0f, 1.0f);",
        "                    }",
        "                    return t * 0.5f;",
        "                } else {",
        "                    float s = std::clamp(val / 2.0f, 0.0f, 1.0f);",
        "                    float t = s;",
        "                    for (int i = 0; i < 4; ++i) {",
        "                        float f = t * t * (3.0f - 2.0f * t) - s;",
        "                        float df = 6.0f * t * (1.0f - t);",
        "                        if (std::abs(df) > 1e-5f) t -= f / df;",
        "                        t = std::clamp(t, 0.0f, 1.0f);",
        "                    }",
        "                    return 0.5f + t * 0.5f;",
        "                }",
        "            }",
        "        );",
        "    };",
        "",
        "    // Symmetric Quadratic Time Range Lambda (-4..0..+4x duration with 1x at 75% dial throw / 3 o'clock)",
        "    auto symmetricQuadraticTimeRange = []() {",
        "        return juce::NormalisableRange<float>(",
        "            -4.0f, 4.0f,",
        "            [](float, float, float norm) {",
        "                float n = (norm - 0.5f) * 2.0f;",
        "                float sign = (n < 0.0f) ? -1.0f : 1.0f;",
        "                return sign * 4.0f * (n * n);",
        "            },",
        "            [](float, float, float val) {",
        "                float sign = (val < 0.0f) ? -1.0f : 1.0f;",
        "                float mag = std::abs(val);",
        "                float n = sign * 0.5f * std::sqrt(std::clamp(mag, 0.0f, 4.0f));",
        "                return 0.5f + 0.5f * n;",
        "            }",
        "        );",
        "    };",
        "",
        "    // Asymmetric Bipolar Tilt Detent Lambda (-12..0..+6 dB/oct with 12 o'clock detent at 0.00)",
        "    auto asymmetricTiltRange = []() {",
        "        return juce::NormalisableRange<float>(",
        "            -12.0f, 6.0f,",
        "            [](float, float, float norm) {",
        "                return (norm < 0.5f) ? -12.0f * (1.0f - 2.0f * norm)",
        "                                     :   6.0f * (2.0f * norm - 1.0f);",
        "            },",
        "            [](float, float, float val) {",
        "                return (val < 0.0f) ? 0.5f * (1.0f + val / 12.0f)",
        "                                    : 0.5f + (val / 12.0f);",
        "            },",
        "            [](float, float, float val) {",
        "                return juce::jlimit(-12.0f, 6.0f, val);",
        "            }",
        "        );",
        "    };",
        ""
    ]

    for p in params:
        pid = p["id"]
        pname = p["name"].replace('"', '\\"')
        ptype = p["type"]
        pdef = p.get("default")
        
        lines.append(f"    // {pid} [{p.get('category', 'general')}]")
        
        if ptype == "choice":
            choices = p.get("choices", [])
            choice_items = ", ".join([f'"{c}"' for c in choices])
            if isinstance(pdef, int):
                def_idx = pdef if 0 <= pdef < len(choices) else 0
            elif pdef in choices:
                def_idx = choices.index(pdef)
            else:
                def_idx = 0
            lines.append(f"    layout.add(std::make_unique<juce::AudioParameterChoice>(")
            lines.append(f"        juce::ParameterID{{{ns}::Ids::{pid}, 1}}, {ns}::Names::{pid},")
            lines.append(f"        juce::StringArray{{{choice_items}}}, {def_idx}));")

        elif ptype == "bool":
            b_val = "true" if pdef is True or str(pdef).lower() == "true" else "false"
            lines.append(f"    layout.add(std::make_unique<juce::AudioParameterBool>(")
            lines.append(f"        juce::ParameterID{{{ns}::Ids::{pid}, 1}}, {ns}::Names::{pid}, {b_val}));")

        elif ptype == "int":
            rng = p.get("range", [0, 10])
            lines.append(f"    layout.add(std::make_unique<juce::AudioParameterInt>(")
            lines.append(f"        juce::ParameterID{{{ns}::Ids::{pid}, 1}}, {ns}::Names::{pid}, {int(rng[0])}, {int(rng[1])}, {int(pdef)}));")

        elif ptype == "float":
            if p.get("custom_range") == "sCurveOctaveRange":
                lines.append(f"    layout.add(std::make_unique<juce::AudioParameterFloat>(")
                lines.append(f"        juce::ParameterID{{{ns}::Ids::{pid}, 1}}, {ns}::Names::{pid}, sCurveOctaveRange(), {float(pdef):.4f}f));")
            elif p.get("custom_range") == "symmetricQuadraticTimeRange":
                lines.append(f"    layout.add(std::make_unique<juce::AudioParameterFloat>(")
                lines.append(f"        juce::ParameterID{{{ns}::Ids::{pid}, 1}}, {ns}::Names::{pid}, symmetricQuadraticTimeRange(), {float(pdef):.4f}f));")
            elif p.get("custom_range") == "asymmetricTiltRange":
                lines.append(f"    layout.add(std::make_unique<juce::AudioParameterFloat>(")
                lines.append(f"        juce::ParameterID{{{ns}::Ids::{pid}, 1}}, {ns}::Names::{pid}, asymmetricTiltRange(), {float(pdef):.4f}f));")
            elif "skew_center" in p or "skew_mid" in p:
                rng = p.get("range", [0.0, 1.0])
                sk = p.get("skew_center", p.get("skew_mid"))
                lines.append(f"    {{")
                lines.append(f"        juce::NormalisableRange<float> nr{{{float(rng[0]):.4f}f, {float(rng[1]):.4f}f}};")
                lines.append(f"        nr.setSkewForCentre({float(sk):.4f}f);")
                lines.append(f"        layout.add(std::make_unique<juce::AudioParameterFloat>(")
                lines.append(f"            juce::ParameterID{{{ns}::Ids::{pid}, 1}}, {ns}::Names::{pid}, nr, {float(pdef):.4f}f));")
                lines.append(f"    }}")
            elif "step" in p or "skew" in p:
                rng = p.get("range", [0.0, 1.0])
                step = p.get("step", 0.0)
                skew = p.get("skew", 1.0)
                lines.append(f"    layout.add(std::make_unique<juce::AudioParameterFloat>(")
                lines.append(f"        juce::ParameterID{{{ns}::Ids::{pid}, 1}}, {ns}::Names::{pid},")
                lines.append(f"        juce::NormalisableRange<float>{{{float(rng[0]):.4f}f, {float(rng[1]):.4f}f, {float(step):.4f}f, {float(skew):.4f}f}}, {float(pdef):.4f}f));")
            else:
                rng = p.get("range", [0.0, 1.0])
                lines.append(f"    layout.add(std::make_unique<juce::AudioParameterFloat>(")
                lines.append(f"        juce::ParameterID{{{ns}::Ids::{pid}, 1}}, {ns}::Names::{pid}, {float(rng[0]):.4f}f, {float(rng[1]):.4f}f, {float(pdef):.4f}f));")

        lines.append("")

    lines.extend([
        "    return layout;",
        "}",
        f"}} // namespace {ns}",
        ""
    ])

    return "\n".join(lines)


def process_plugin(plugin_name: str, verify_only: bool = False) -> bool:
    contract = load_contract(plugin_name)
    plugin = contract["plugin"]
    
    ids_content = generate_ids_header(contract)
    layout_content = generate_layout_header(contract)

    target_dir = ROOT_TKS / "source" / plugin.lower()
    if not target_dir.exists():
        target_dir.mkdir(parents=True, exist_ok=True)

    prefix = resolve_plugin_prefix(plugin)
    ids_file = target_dir / f"{prefix}ParameterIds.h"
    layout_file = target_dir / f"{prefix}ParameterLayout.h"

    ids_norm = ids_content.replace("\r\n", "\n")
    layout_norm = layout_content.replace("\r\n", "\n")

    def read_norm(fp: Path) -> str:
        return fp.read_text(encoding="utf-8").replace("\r\n", "\n") if fp.exists() else ""

    if verify_only:
        ids_match = ids_file.exists() and read_norm(ids_file) == ids_norm
        layout_match = layout_file.exists() and read_norm(layout_file) == layout_norm
        if ids_match and layout_match:
            print(f"[{plugin}] VERIFY PASSED: C++ code matches contract 100%.")
            return True
        else:
            print(f"[{plugin}] VERIFY FAILED: C++ parameter files have drifted from contract!", file=sys.stderr)
            return False

    # Write only if changed to avoid updating mtime and triggering full C++ rebuilds
    wrote_any = False
    if not ids_file.exists() or read_norm(ids_file) != ids_norm:
        ids_file.write_text(ids_content, encoding="utf-8", newline="\n")
        wrote_any = True

    if not layout_file.exists() or read_norm(layout_file) != layout_norm:
        layout_file.write_text(layout_content, encoding="utf-8", newline="\n")
        wrote_any = True

    if wrote_any:
        print(f"[{plugin}] Successfully generated (updated):")
        print(f"  - {ids_file} ({len(contract['parameters'])} parameter IDs)")
        print(f"  - {layout_file} (createLayout function)")
    else:
        print(f"[{plugin}] Headers up to date (0 rebuild tokens, mtime preserved).")
    return True


def main():
    parser = argparse.ArgumentParser(description="Single Source of Truth APVTS Code Generator")
    parser.add_argument("--plugin", "-p", type=str, default="hastur", help="Plugin name (e.g. hastur)")
    parser.add_argument("--verify", action="store_true", help="Verify that on-disk C++ matches contract")
    parser.add_argument("--all", action="store_true", help="Process all contracts in contracts/")

    args = parser.parse_args()

    if args.all:
        contracts_dir = ROOT_TKS / "contracts"
        all_passed = True
        for yml in contracts_dir.glob("*.yaml"):
            p_name = yml.stem
            res = process_plugin(p_name, verify_only=args.verify)
            if not res: all_passed = False
        sys.exit(0 if all_passed else 1)
    else:
        res = process_plugin(args.plugin, verify_only=args.verify)
        sys.exit(0 if res else 1)


if __name__ == "__main__":
    main()
